def clean(lines):
    """Only XX-XXXX-XXXXXX entries, upper case, no repeats."""
    out = []
    for line in lines:
        a = line.strip().upper()
        if ASSET_TYPE_FORMAT.match(a) and a not in out:
            out.append(a)
    return out


def load():
    if os.path.isfile(OVERRIDE_FILE):
        with open(OVERRIDE_FILE, encoding="utf-8-sig") as f:
            types = clean(f.read().split())
        if types:
            return set(types)
    return set(clean(DEFAULT.split()))
